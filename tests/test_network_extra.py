def _write_nss(tmp_path: Path, line: str) -> tuple[Path, Path]:
    nss = tmp_path / "nsswitch.conf"
    nss.write_text(line + "\n", encoding="utf-8")
    resolv = tmp_path / "resolv.conf"
    return nss, resolv


